# Trainer computes real total_steps from dataloader; this is only a fallback.
export BOK_TOTAL_STEPS=${BOK_TOTAL_STEPS:-${_V36_DEFAULT_BOK_TOTAL_STEPS}}

# ---- Grad-safety: skip unsafe updates, do not modify LR automatically ----
export GRAD_SPIKE_PROTECT=${GRAD_SPIKE_PROTECT:-1}
export GRAD_SPIKE_THRESHOLD=${GRAD_SPIKE_THRESHOLD:-3.0}
