export GRAD_SPIKE_BRAKE_MAX=${GRAD_SPIKE_BRAKE_MAX:-1000000}
export GRAD_NONFINITE_BRAKE_MAX=${GRAD_NONFINITE_BRAKE_MAX:-1000000}

# ---- Checkpoint/log identity ----
export TRAIN_SAVE_FREQ=${TRAIN_SAVE_FREQ:-${_V36_DEFAULT_SAVE_FREQ}}
export TRAIN_SAVE_LIMIT=${TRAIN_SAVE_LIMIT:-3}
export TRAIN_VAL_FREQ=${TRAIN_VAL_FREQ:-30}
export V31_EXPERIMENT_NAME=${V31_EXPERIMENT_NAME:-StepCount-7B_v36_dense_11_50_maskcomplete38332_ckpt476_${_V36_TOTAL_GPUS}gpu_$(date +%Y%m%d_%H%M)}
export V36_SAVE_ROOT=${V36_SAVE_ROOT:-${EASYR1_CHECKPOINT_ROOT}}
mkdir -p "${V36_SAVE_ROOT}"
export V31_SAVE_CHECKPOINT_PATH=${V31_SAVE_CHECKPOINT_PATH:-${V36_SAVE_ROOT}/${V31_EXPERIMENT_NAME}}
mkdir -p "${V31_SAVE_CHECKPOINT_PATH}"

# Persist the dataset and topology identity beside global_step_* so resume does
# not have to infer critical state from a user-editable experiment name.
_V36_RUN_MANIFEST="${V31_SAVE_CHECKPOINT_PATH}/v36_run_manifest.tsv"
_V36_RUN_MANIFEST_TMP="${_V36_RUN_MANIFEST}.tmp.$$"
{
  printf 'manifest_version\t1\n'
  printf 'STEPCOUNT_TRAIN_DATA\t%s\n' "${STEPCOUNT_TRAIN_DATA}"
  printf 'MODEL_PATH\t%s\n' "${MODEL_PATH}"
  printf 'STEPCOUNT_MASKS_METADATA\t%s\n' "${STEPCOUNT_MASKS_METADATA}"
  printf 'STEPCOUNT_MASKS_DIR\t%s\n' "${STEPCOUNT_MASKS_DIR}"
  printf 'V31_EXPERIMENT_NAME\t%s\n' "${V31_EXPERIMENT_NAME}"
  printf 'TOTAL_GPUS\t%s\n' "${_V36_TOTAL_GPUS}"
  printf 'ROLLOUT_N\t%s\n' "${ROLLOUT_N}"
  printf 'ADV_ESTIMATOR\t%s\n' "${ADV_ESTIMATOR}"
  printf 'created_at\t%s\n' "$(date '+%F %T %Z')"
} > "${_V36_RUN_MANIFEST_TMP}"
