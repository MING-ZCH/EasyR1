echo "================================================================"
echo "[V36-dense-11-50] clean_start=1 model=${MODEL_PATH}"
echo "[V36-dense-11-50] hardware_profile=${STEPCOUNT_HARDWARE_PROFILE}"
echo "[V36-dense-11-50] runtime wandb=${WANDB_MODE} alloc=${PYTORCH_CUDA_ALLOC_CONF} seed=${PYTHONHASHSEED}"
echo "[V36-dense-11-50] data=${STEPCOUNT_TRAIN_DATA}"
echo "[V36-dense-11-50] val=${STEPCOUNT_VAL_DATA}"
echo "[V36-dense-11-50] masks_meta=${STEPCOUNT_MASKS_METADATA}"
echo "[V36-dense-11-50] masks_dir=${STEPCOUNT_MASKS_DIR}"
echo "[V36-dense-11-50] nnodes=${V31_NNODES} gpus_per_node=${V31_N_GPUS_PER_NODE} rollout_batch=${V31_ROLLOUT_BATCH_SIZE} global_batch=${V31_GLOBAL_BATCH_SIZE} val_batch=${V31_VAL_BATCH_SIZE} filter_num_proc=${V31_FILTER_OVERLONG_NUM_PROC}"
echo "[V36-dense-11-50] turns=${INTERLEAVED_MAX_TURNS} adaptive=${INTERLEAVED_ADAPTIVE_MAX_TURNS} margin=${INTERLEAVED_ADAPTIVE_MAX_TURNS_MARGIN} point_answer_budget=${INTERLEAVED_POINT_TURN_USE_ANSWER_BUDGET} point_tokens=${INTERLEAVED_PER_TURN_MAX_TOKENS} answer_tokens=${INTERLEAVED_ANSWER_TURN_MAX_TOKENS}"
echo "[V36-dense-11-50] prompt_len=${V31_MAX_PROMPT_LENGTH} response_len=${V31_MAX_RESPONSE_LENGTH} model_len=${V31_MAX_MODEL_LEN} batched_tokens=${V31_MAX_NUM_BATCHED_TOKENS} blocks=${EASYR1_VLLM_NUM_GPU_BLOCKS} enforce_eager=${V31_ENFORCE_EAGER}"
echo "[V36-dense-11-50] reward w=${ANSWER_WEIGHT}/${POINT_WEIGHT}/${TRAJECTORY_FORMAT_WEIGHT} wrong_cap=${TRAJ_DENSE_CONTINUOUS_WRONG_CAP} within1=${TRAJ_DENSE_CONTINUOUS_WITHIN1_CAP}"
echo "[V36-dense-11-50] adv=${ADV_ESTIMATOR} process_reward=${PROCESS_REWARD_ENABLE} kl=${KL_COEF} kl_type=${KL_TYPE} use_kl_loss=${USE_KL_LOSS} target=${KL_TARGET} horizon=${KL_HORIZON}"
echo "[V36-dense-11-50] rollout_n=${ROLLOUT_N} temp=${ROLLOUT_TEMPERATURE} lr=${ACTOR_LR} gpu_mem=${V31_GPU_MEM_UTIL} micro=${V31_MICRO_BATCH_UPDATE}/${V31_MICRO_BATCH_EXP} ulysses_enable=${V36_ENABLE_ULYSSES_SP} ulysses_sp=${V31_ULYSSES_SEQUENCE_PARALLEL_SIZE} reward_workers=${REWARD_NUM_WORKERS} mask_cache_max=${STEPCOUNT_MASK_CACHE_MAX}"
